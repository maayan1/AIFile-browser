// Generates src/protocol/generated.ts from protocol/schemas/*.schema.json.
// Runs from predev / prebuild / pretest; the output is never committed.
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaDir = path.resolve(here, "../../protocol/schemas");
const outFile = path.resolve(here, "../src/protocol/generated.ts");

const files = (await readdir(schemaDir)).filter((f) => f.endsWith(".schema.json")).sort();
if (files.length === 0) throw new Error(`no schemas in ${schemaDir}`);

const parts = [];
const typeNames = [];
for (const file of files) {
  const ts = await compileFromFile(path.join(schemaDir, file), {
    bannerComment: "",
    additionalProperties: false,
    style: { singleQuote: false },
  });
  parts.push(ts.trim());
  // The message type is the one named by the schema's title; definitions add helper types.
  const { title } = JSON.parse(await readFile(path.join(schemaDir, file), "utf8"));
  if (typeof title !== "string" || !ts.includes(`export interface ${title} `)) {
    throw new Error(`no exported type named by the title of ${file}`);
  }
  typeNames.push(title);
}

const banner =
  "/* Generated by scripts/gen-protocol-types.mjs from protocol/schemas. Do not edit or commit. */\n\n";
const union = `export type ProtocolMessage = ${typeNames.join(" | ")};\n`;
await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(outFile, banner + parts.join("\n\n") + "\n\n" + union, "utf8");
console.log(`protocol types: ${typeNames.join(", ")} -> ${path.relative(process.cwd(), outFile)}`);
